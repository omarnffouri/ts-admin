import 'package:ts_admin/app/modules/hr/domain/entities/personal_infomation_entity.dart';

class PersonalInformationModel extends PersonalInformationEntity {
  const PersonalInformationModel({
    super.applicationId,
    super.companyName,
    super.jobAppliedFor,
    super.jobCategory,
    super.referredBy,
    super.active,
    super.id,
    super.name,
    super.firstName,
    super.middleName,
    super.lastName,
    super.ssNo,
    super.dob,
    super.mobileNumber,
    super.otherMobileNumber,
    super.email,
    super.status,
    super.previousStatus,
    super.originalStatus,
    super.applicationStatus,
    super.isOwnerPartner,
    super.applicationActive,
  });

  factory PersonalInformationModel.fromJson(Map<String, dynamic> json) =>
      PersonalInformationModel(
        applicationId: json["application_id"],
        companyName: json["company_name"],
        jobAppliedFor: json["job_applied_for"],
        jobCategory: json["job_category"],
        referredBy: json["referred_by"],
        active: json["active"],
        id: json["id"],
        name: json["name"],
        firstName: json["first_name"],
        middleName: json["middle_name"],
        lastName: json["last_name"],
        ssNo: json["ss_no"],
        dob: json["dob"],
        mobileNumber: json["mobile_number"],
        otherMobileNumber: json["other_mobile_number"],
        email: json["email"],
        status: json["status"],
        previousStatus: json["previous_status"],
        originalStatus: json["original_status"],
        applicationStatus: json["application_status"],
        isOwnerPartner: json["is_owner_partner"],
        applicationActive: json["application_active"],
      );

  @override
  Map<String, dynamic> toJson() => {
        "application_id": applicationId,
        "company_name": companyName,
        "job_applied_for": jobAppliedFor,
        "job_category": jobCategory,
        "referred_by": referredBy,
        "active": active,
        "id": id,
        "name": name,
        "first_name": firstName,
        "middle_name": middleName,
        "last_name": lastName,
        "ss_no": ssNo,
        "dob": dob,
        "mobile_number": mobileNumber,
        "other_mobile_number": otherMobileNumber,
        "email": email,
        "status": status,
        "previous_status": previousStatus,
        "original_status": originalStatus,
        "application_status": applicationStatus,
        "is_owner_partner": isOwnerPartner,
        "application_active": applicationActive,
      };
}
